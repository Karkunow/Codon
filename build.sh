#!/bin/bash
# Builds libqiskit (Qiskit C API) and libtwirl.dylib, then runs the equivalence tests.
# Needs Rust >= 1.91 and Codon (~/.codon). SKIP_QISKIT=1 reuses an existing qiskit/dist/c.
set -euo pipefail
cd "$(dirname "$0")"

QISKIT=${QISKIT:-$PWD/qiskit}
CODON=${CODON:-$HOME/.codon/bin/codon}
[ -d "$QISKIT" ] || git clone --depth 1 https://github.com/Qiskit/qiskit.git "$QISKIT"
if [ "${SKIP_QISKIT:-0}" != 1 ] || [ ! -f "$QISKIT/dist/c/lib/libqiskit.dylib" ]; then
    make -C "$QISKIT" c  # -> dist/c/include/qiskit.h, dist/c/lib/libqiskit.dylib
fi
INC=$QISKIT/dist/c/include
LIB=$QISKIT/dist/c/lib
# Reference libqiskit through @rpath, not the cargo target path baked into it.
install_name_tool -id @rpath/libqiskit.dylib "$LIB/libqiskit.dylib"
codesign -f -s - "$LIB/libqiskit.dylib" 2>/dev/null  # install_name_tool invalidates the signature

# qk_build.codon: the header facts twirl.codon checks the loaded libqiskit against.
printf '#include <stdio.h>\n#include <qiskit.h>\nint main(void) { printf("%%u", QISKIT_VERSION_HEX); }\n' \
    | cc -x c -I"$INC" -o build_version - && VERSION=$(./build_version) && rm build_version
NUM_GATES=$(( $(grep -oE 'QkGate_[A-Za-z0-9]+ = [0-9]+' "$INC/qiskit/types.h" | awk '{print $3}' | sort -n | tail -1) + 1 ))
cat > qk_build.codon <<EOF
# Generated by build.sh from $INC. Do not edit.
QK_BUILD_VERSION = $VERSION
QK_NUM_GATES = $NUM_GATES
EOF

"$CODON" build -release --relocation-model=pic --lib -o libtwirl.dylib \
    --linker-flags="-L$LIB -lqiskit -Wl,-rpath,$LIB -Wl,-rpath,@loader_path" \
    twirl.codon

if [ -f tests/cases.json ]; then
    for mode in 0 1 2; do TWIRL_FAST_PATH=$mode python3 -I tests/check_codon.py; done
fi

# C++ caller: c++ main.cpp -I. -I$INC -L. -ltwirl -L$LIB -lqiskit -Wl,-rpath,$PWD -Wl,-rpath,$LIB
